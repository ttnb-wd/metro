import "server-only";
import { randomUUID } from "node:crypto";
import type { PrismaClient } from "../db/generated/client";
import { AuthRequestError } from "./request-policy";
import { INTERNAL_AUTH_IP_HEADER } from "./options";

export const INTERNAL_AUTH_SOURCE_HEADER = "x-metro-auth-source";
const limits: Record<string, number> = { "/sign-in/email": 5, "/sign-up/email": 3, "/send-verification-email": 1, "/verify-email": 10, "/update-user": 5, "/request-password-reset": 1, "/reset-password": 5 };
export async function consumeAuthBudget(db: PrismaClient, request: Request) {
  if (request.method !== "POST") return;
  const path = new URL(request.url).pathname.slice("/api/auth".length), max = limits[path];
  if (!max) return;
  async function consume(key: string, maximum: number) {
    const [row] = await db.$queryRaw<Array<{ count: number }>>`INSERT INTO metro_rate_limit (id,key,count,"lastRequest")
      VALUES (${randomUUID()},${key},1,(extract(epoch FROM clock_timestamp())*1000)::bigint)
      ON CONFLICT(key) DO UPDATE SET count=CASE WHEN metro_rate_limit."lastRequest" < (extract(epoch FROM clock_timestamp())*1000)::bigint-60000 THEN 1 ELSE LEAST(metro_rate_limit.count+1,1001) END,
      "lastRequest"=CASE WHEN metro_rate_limit."lastRequest" < (extract(epoch FROM clock_timestamp())*1000)::bigint-60000 THEN (extract(epoch FROM clock_timestamp())*1000)::bigint ELSE metro_rate_limit."lastRequest" END RETURNING count`;
    if (row.count > maximum) throw new AuthRequestError(429, "RATE_LIMITED");
  }
  // Atomic across serverless instances. Key material was generated by the
  // server, never accepted from a client. Per-account login does not lock NAT peers.
  await consume(`auth-account:${path}:${request.headers.get(INTERNAL_AUTH_IP_HEADER)}`, max);
  const source = request.headers.get(INTERNAL_AUTH_SOURCE_HEADER);
  if (source && path !== "/sign-in/email") await consume(`auth-source:${source}`, 60);
}
